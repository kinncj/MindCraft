import { chromium } from '@playwright/test';
const out = process.argv[2];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text().slice(0, 300)); });
await page.goto('http://localhost:4199/');
await page.waitForTimeout(1500);
await page.getByRole('button', { name: /Let's build!/ }).click();
await page.waitForFunction(() => window.mindcraftDebug?.isReady() === true, undefined, { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/cinema-classic.png` });
await page.getByRole('button', { name: 'Open the menu' }).click();
await page.getByRole('button', { name: /World looks/ }).click();
await page.waitForTimeout(400);
await page.getByRole('button', { name: /Cinema/ }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/cinema-menu.png` });
await page.getByRole('button', { name: /^Close/ }).first().click();
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/cinema-round.png` });
const t = await page.evaluate(() => window.mindcraftDebug?.timing?.() ?? null);
console.log('timing', JSON.stringify(t));
console.log('errors', JSON.stringify(errors, null, 1));
await browser.close();
